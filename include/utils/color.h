// Begin include guard to prevent multiple inclusions of this header.
#ifndef COLOR_H
// Define the include guard symbol for the color header.
#define COLOR_H

// ANSI escape sequence to reset all terminal text attributes to default.
#define RESET       "\033[0m"
// ANSI escape sequence for black foreground text.
#define BLACK       "\033[30m"             /* Black */
// ANSI escape sequence for red foreground text.
#define RED         "\033[31m"             /* Red */
// ANSI escape sequence for green foreground text.
#define GREEN       "\033[32m"             /* Green */
// ANSI escape sequence for yellow foreground text.
#define YELLOW      "\033[33m"             /* Yellow */
// ANSI escape sequence for blue foreground text.
#define BLUE        "\033[34m"             /* Blue */
// ANSI escape sequence for magenta foreground text.
#define MAGENTA     "\033[35m"             /* Magenta */
// ANSI escape sequence for cyan foreground text.
#define CYAN        "\033[36m"             /* Cyan */
// ANSI escape sequence for white foreground text.
#define WHITE       "\033[37m"             /* White */
// ANSI escape sequence for red-purple (bright magenta) foreground text.
#define REDPURPLE   "\033[95m"             /* Red Purple */
// ANSI escape sequence for bold black foreground text.
#define BOLDBLACK   "\033[1m\033[30m"      /* Bold Black */
// ANSI escape sequence for bold red foreground text.
#define BOLDRED     "\033[1m\033[31m"      /* Bold Red */
// ANSI escape sequence for bold green foreground text.
#define BOLDGREEN   "\033[1m\033[32m"      /* Bold Green */
// ANSI escape sequence for bold yellow foreground text.
#define BOLDYELLOW  "\033[1m\033[33m"      /* Bold Yellow */
// ANSI escape sequence for bold blue foreground text.
#define BOLDBLUE    "\033[1m\033[34m"      /* Bold Blue */
// ANSI escape sequence for bold magenta foreground text.
#define BOLDMAGENTA "\033[1m\033[35m"      /* Bold Magenta */
// ANSI escape sequence for bold cyan foreground text.
#define BOLDCYAN    "\033[1m\033[36m"      /* Bold Cyan */
// ANSI escape sequence for bold white foreground text.
#define BOLDWHITE   "\033[1m\033[37m"      /* Bold White */
// ANSI escape sequence for bold red-purple foreground text.
#define BOLDREDPURPLE   "\033[1m\033[95m"  /* Bold Red Purple */

// End of the color header include guard.
#endif // COLOR_H
